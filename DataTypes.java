public class DataTypes {
    
    public static void main(String[] args) {
        //Integer Datatype
        byte a = 5;
        short year = 2026;
        int salary = 100000;
        long population = 80000000000L;

        //Floating point Datatype
        float percentage = 49.75f;
        double pi = 3.148592848;
        
        //Character 
        char grade= 'A';

        //booleean
        boolean ispassed= true;


        System.out.println("Primitive data type ");

        System.out.println("Byte value :"+a);
        System.out.println("Short value :"+year);
        System.out.println("Int value"+salary);
        System.out.println("Long value "+population);
        System.out.println("Floating point value "+percentage);
        System.out.println("Double "+pi);

        System.out.println("Char value "+grade);

        System.out.println("boolean "+ispassed);


        
    }
}
